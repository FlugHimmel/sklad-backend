# По умолчанию — все shipped (архив).
# Исключения (в работе и новые):

_ORDER_STATUS = {
    # В работе — не отгружены, quantity_shipped = 0
    "93м": "in_work",
    "97м": "in_work",
    "96м": "in_work",
    "95м": "in_work",

    # Новые — ещё не начали, quantity_shipped = 0
    "100-М": "new",
    "101-М": "new",
    "105-М": "new",
    "103-М": "new",
    "102-М": "new",
}

# Всё остальное → shipped (архив)


def _get_status(number: str) -> str:
    return _ORDER_STATUS.get(number, "shipped")


def _is_shipped_status(status: str) -> bool:
    return status in ("shipped", "closed")


def _parse_date(s):
    if s is None:
        return None
    if isinstance(s, date):
        return s
    s = str(s).strip()
    if not s:
        return None
    for fmt in ("%Y-%m-%d", "%d.%m.%Y", "%d.%m.%y"):
        try:
            return datetime.strptime(s, fmt).date()
        except ValueError:
            continue
    return None


def _clean_number(n):
    """'65-м 12.01.2026' → '65-м'. '74-М от 04.03.2026' → '74-М'."""
    s = str(n).strip()
    # убираем даты в конце
    for sep in (" от ", " ", "\t"):
        if sep in s:
            # отрезаем если после sep идёт дата или цифры с точками
            head, _, tail = s.partition(sep)
            tail = tail.strip()
            # если tail — дата или начинается с цифры+точки
            if tail and (tail[0].isdigit() or tail.startswith("от")):
                # проверяем похоже ли на дату
                import re
                if re.match(r"^\d{2}\.\d{2}\.\d{4}$", tail) or \
                   re.match(r"^\d{2}\.\d{2}\.\d{2}$", tail) or \
                   tail.startswith("от "):
                    return head.strip()
    return s


class Command(BaseCommand):
    help = ("Импорт старых заказов (архив). Идемпотентно: пропускает уже существующие. "
            "Все заказы создаются со quantity_shipped = quantity_planned.")

    def add_arguments(self, parser):
        parser.add_argument("--dry-run", action="store_true",
                            help="Показать что будет создано, без записи")

    def handle(self, *args, **options):
        dry_run = options["dry_run"]

        created_orders = 0
        created_lines = 0
        skipped_orders = 0
        created_products = set()

        self.stdout.write("Импорт старых заказов...")
        self.stdout.write("")

        for (number, order_date, due_date, lines) in ORDERS_DATA:
            clean_number = _clean_number(number)
            order_status = _get_status(clean_number)
            is_archived = _is_shipped_status(order_status)

            # UPDATE-EXISTING: если заказ уже есть — обновляем статус и shipped_qty
            existing = Order.objects.filter(number=clean_number).first()
            if existing:
                if not dry_run:
                    with transaction.atomic():
                        existing.status = order_status
                        existing.save(update_fields=["status", "updated_at"])
                        for ln in existing.lines.all():
                            ln.quantity_shipped = (ln.quantity_planned
                                                   if is_archived
                                                   else Decimal("0"))
                            if not is_archived:
                                ln.shipped_date = None
                            ln.save(update_fields=[
                                "quantity_shipped", "shipped_date",
                            ])
                self.stdout.write(
                    f"  🔄 {clean_number:12s} [{order_status:8s}] — обновлён"
                )
                skipped_orders += 1
                continue

            if dry_run:
                st = _get_status(_clean_number(number))
                self.stdout.write(
                    f"  ➕ {_clean_number(number):12s} [{st:8s}] "
                    f"{len(lines)} строк"
                )
                created_orders += 1
                created_lines += len(lines)
                continue

            clean_number = _clean_number(number)
            order_status = _get_status(clean_number)
            is_archived = _is_shipped_status(order_status)

            with transaction.atomic():
                order = Order.objects.create(
                    number=clean_number,
                    kind="production",
                    status=order_status,
                    due_date=_parse_date(due_date),
                    comment=(f"Архив (заказ от {order_date})"
                             if is_archived
                             else f"Заказ от {order_date}"),
                )
                created_orders += 1

                for (cast_art, part_art, name, qty,
                     ready, shipped, w_kg, places, cmt) in lines:

                    casting = None
                    if cast_art:
                        casting = self._get_or_create(
                            cast_art, "casting", created_products)

                    product = self._get_or_create(
                        part_art, "part", created_products)

                    qty_dec = Decimal(str(qty))
                    wg = None
                    if w_kg is not None:
                        wg = Decimal(str(w_kg)) * Decimal("1000")

                    OrderLine.objects.create(
                        order=order,
                        product=product,
                        casting=casting,
                        name=name[:255],
                        quantity_planned=qty_dec,
                        # Архив — считаем отгруженным.
                        # В работе / новые — 0 (ещё не отгружено).
                        quantity_shipped=(qty_dec if is_archived
                                          else Decimal("0")),
                        ready_date=_parse_date(ready),
                        shipped_date=(_parse_date(shipped)
                                      if is_archived else None),
                        reserve_qty=Decimal("0"),
                        places=int(places) if places else None,
                        weight_g=wg,
                        comment=cmt or "",
                    )
                    created_lines += 1

        self.stdout.write("")
        self.stdout.write(self.style.SUCCESS(
            f"✅ Заказов: {created_orders}, строк: {created_lines}, "
            f"пропущено: {skipped_orders}"
        ))
        if created_products:
            self.stdout.write(self.style.WARNING(
                f"⚠️  Создано неактивных продуктов: {len(created_products)}"
            ))
            for p in sorted(created_products)[:30]:
                self.stdout.write(f"     {p}")
            if len(created_products) > 30:
                self.stdout.write(f"     ...и ещё {len(created_products) - 30}")

    def _get_or_create(self, article, ptype, created_set):
        if not article:
            return None
        art = article.split("/")[0].strip() if "/" in article else article
        p = Product.objects.filter(article__iexact=art).first()
        if p:
            return p
        p = Product.objects.create(
            article=art,
            name=f"(импорт) {art}",
            product_type=ptype,
            is_active=False,
        )
        created_set.add(f"{ptype}:{art}")
        return p
